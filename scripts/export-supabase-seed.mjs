function readJson(filePath) {
  return JSON.parse(readFileSync(join(root, filePath), "utf8"));
}

function slugify(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[\u0027\u2018\u2019\u02bc]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function normalizeBook(raw) {
  const id = String(raw.id || "").trim().toLowerCase();
  const manifest = manifestFor(raw, id);
  const title = String(raw.title || manifest?.title || id || "Untitled").trim();
  const tags = Array.isArray(raw.tags) ? raw.tags.map(String).filter(Boolean) : [];
  const wordCount = Number(raw.wordCount || manifest?.wordCount || 0);
  const slug = slugify(String(raw.slug || title || manifest?.slug || id));
  const slugAliases = [...new Set([
    id,
    slugify(String(manifest?.slug || "")),
    slugify(String(raw.title || "")),
  ].filter(alias => alias && alias !== slug))];

  return {
    id,
    slug,
    title,
    subtitle: String(raw.subtitle || "").trim(),
    creator: String(raw.creator || raw.author || "James Johnson").trim(),
    description: String(raw.description || "").trim(),
    status: String(raw.status || "ready").trim().toLowerCase(),
    visibility: raw.archive || String(raw.visibility || "main").toLowerCase() === "archive" ? "archive" : "main",
    archiveCategory: String(raw.archiveCategory || raw.category || "").trim(),
    primaryCategory: primaryCategoryFor(tags),
    coverFile: String(raw.coverFile || "").trim(),
    bookFile: String(raw.bookFile || manifest?.sourceFile || "").trim(),
    contentKey: String(manifest?.path || "").trim(),
    wordCount,
    readingMinutes: Number(raw.readingMinutes || Math.ceil(wordCount / 180) || 0),
    readingLabel: String(raw.readingLabel || "").trim(),
    chapterCount: Number(raw.chapterCount || manifest?.sectionCount || 0),
    tags,
    slugAliases,
    metadata: {
      series: String(raw.series || "").trim(),
      similar: Array.isArray(raw.similar) ? raw.similar.map(item => String(item).trim().toLowerCase()).filter(Boolean) : [],
      hiddenShelves: Array.isArray(raw.hiddenShelves) ? raw.hiddenShelves : [],
    },
  };
}

function manifestFor(raw, id) {
  const bookStem = String(raw.bookFile || "").replace(/\.(epub|json)$/i, "").toLowerCase();
  return manifestBooks.find(item => {
    const manifestId = String(item.id || "").toLowerCase();
    const sourceStem = String(item.sourceFile || "").replace(/\.(epub|json)$/i, "").toLowerCase();
    return manifestId === id || sourceStem === id || Boolean(bookStem && sourceStem === bookStem);
  });
}

function primaryCategoryFor(tags) {
  return PRIMARY_CATEGORIES.find(([, categoryTags]) => tags.some(tag => categoryTags.includes(tag)))?.[0] || "Library";
}

function normalizeSeriesItems() {
  const items = [
    ...(Array.isArray(rawPaths.series) ? rawPaths.series : []),
    ...(Array.isArray(rawPaths.paths) ? rawPaths.paths : []),
    ...(Array.isArray(rawPaths.tagPaths) ? rawPaths.tagPaths : []),
    ...(Array.isArray(rawPaths.recommendedReading) ? rawPaths.recommendedReading : []),
  ];
  const seen = new Set();

  return items
    .filter(item => !item.deleted && item.id && item.title && Array.isArray(item.books) && item.books.length)
    .map((item, index) => {
      const id = slugify(String(item.id || item.title || ""));
      const title = String(item.title || id).trim();
      const is101 = id.includes("101") || /\b101\b/.test(title);
      return {
        id: is101 ? "101" : id,
        slug: is101 ? "101" : id || slugify(title),
        title: is101 ? "JJ University 101" : title,
        description: String(item.description || `A JJ University reading sequence around ${title}.`).trim(),
        level: String(item.level || "starter").trim(),
        kind: String(item.kind || item.type || "series").trim(),
        tags: Array.isArray(item.tags) ? item.tags.map(String).filter(Boolean) : [],
        sortOrder: index,
        metadata: { sourceId: item.id, type: item.type || item.kind || "series" },
        books: item.books.map((book, bookIndex) => ({
          id: String(book.id || "").trim().toLowerCase(),
          position: Number(book.order || book.position || bookIndex + 1),
          note: String(book.note || "").trim(),
        })).filter(book => book.id),
      };
    })
    .filter(item => {
      if (seen.has(item.slug)) return false;
      seen.add(item.slug);
      return item.books.length;
    });
}

function upsertBookCatalog(items) {
  const columns = [
    "id", "slug", "title", "subtitle", "creator", "description", "status", "visibility",
    "archive_category", "primary_category", "cover_file", "book_file", "content_key",
    "word_count", "reading_minutes", "reading_label", "chapter_count", "tags", "slug_aliases", "metadata",
  ];
  const rows = items.map(book => `(${[
    q(book.id),
    q(book.slug),
    q(book.title),
    q(book.subtitle),
    q(book.creator),
    q(book.description),
    q(book.status),
    q(book.visibility),
    q(book.archiveCategory),
    q(book.primaryCategory),
    q(book.coverFile),
    q(book.bookFile),
    q(book.contentKey),
    n(book.wordCount),
    n(book.readingMinutes),
    q(book.readingLabel),
    n(book.chapterCount),
    textArray(book.tags),
    textArray(book.slugAliases),
    jsonb(book.metadata),
  ].join(", ")})`);

  return upsert("book_catalog", columns, rows, "id", columns.filter(column => column !== "id"));
}

function upsertSlugAliases(items) {
  const rows = items.map(item => `(${q(item.alias)}, ${q(item.bookId)})`);
  return upsert("book_slug_aliases", ["alias", "book_id"], rows, "alias", ["book_id"]);
}

function upsertSeries(items) {
  const columns = ["id", "slug", "title", "description", "level", "kind", "tags", "published", "sort_order", "metadata"];
  const rows = items.map(item => `(${[
    q(item.id),
    q(item.slug),
    q(item.title),
    q(item.description),
    q(item.level),
    q(item.kind),
    textArray(item.tags),
    "true",
    n(item.sortOrder),
    jsonb(item.metadata),
  ].join(", ")})`);
  return upsert("series", columns, rows, "id", columns.filter(column => column !== "id"));
}

function upsertSeriesBooks(items) {
  const rows = items.map(item => `(${q(item.seriesId)}, ${q(item.bookId)}, ${n(item.position)}, ${q(item.note)})`);
  return upsert("series_books", ["series_id", "book_id", "position", "note"], rows, "series_id, book_id", ["position", "note"]);
}

function upsertPrintProducts(items) {
  const columns = [
    "slug",
    "title",
    "kicker",
    "subtitle",
    "description",
    "status",
    "price_cents",
    "stripe_price_id",
    "lulu_project_id",
    "lulu_pod_package_id",
    "public_interior_url",
    "public_cover_url",
    "metadata",
  ];
  const rows = items.map(item => `(${[
    q(item.slug),
    q(item.title),
    q(item.kicker),
    q(item.subtitle),
    q(item.description),
    q(item.status),
    item.targetPriceCents == null ? "null" : n(item.targetPriceCents),
    item.stripePriceId ? q(item.stripePriceId) : "null",
    item.luluProjectId ? q(item.luluProjectId) : "null",
    item.podPackageId ? q(item.podPackageId) : "null",
    item.publicInteriorUrl ? q(item.publicInteriorUrl) : "null",
    item.publicCoverUrl ? q(item.publicCoverUrl) : "null",
    jsonb({
      source: "static-print-plan",
      sku: item.sku || item.slug,
      kind: item.kind || "collection",
      priceHint: item.priceHint || "",
      printStatus: item.printStatus || "draft",
      salesStatus: item.salesStatus || "not-for-sale",
      podPackageId: item.podPackageId || "",
      publicInteriorUrl: item.publicInteriorUrl || "",
      publicCoverUrl: item.publicCoverUrl || "",
      actualInteriorPages: item.actualInteriorPages || null,
      generatedAt: item.generatedAt || "",
      componentProductSlugs: item.componentProductSlugs || [],
      format: item.format || {},
      coverTheme: item.coverTheme || {},
      includedLine: item.includedLine || "",
    }),
  ].join(", ")})`);
  return upsert("print_products", columns, rows, "slug", columns.filter(column => column !== "slug"));
}

function upsertPrintProductBooks(items) {
  const rows = items.map(item => `(${q(item.productSlug)}, ${q(item.bookId)}, ${n(item.position)})`);
  return upsert("print_product_books", ["product_slug", "book_id", "position"], rows, "product_slug, book_id", ["position"]);
}

function upsert(table, columns, rows, conflictTarget, updateColumns) {
  if (!rows.length) return `-- No rows for ${table}.`;
  return [
    `insert into public.${table} (${columns.join(", ")})`,
    "values",
    rows.join(",\n"),
    `on conflict (${conflictTarget}) do update set`,
    updateColumns.map(column => `  ${column} = excluded.${column}`).join(",\n") + ";",
    "",
  ].join("\n");
}

function q(value) {
  return `'${String(value ?? "").replace(/'/g, "''")}'`;
}

function n(value) {
  return String(Number.isFinite(Number(value)) ? Number(value) : 0);
}

function textArray(items) {
  const values = (Array.isArray(items) ? items : []).map(item => String(item)).filter(Boolean);
  if (!values.length) return "'{}'::text[]";
  return `array[${values.map(q).join(", ")}]::text[]`;
}

function jsonb(value) {
  return `${q(JSON.stringify(value ?? {}))}::jsonb`;
}
